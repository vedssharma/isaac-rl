"""The Phase 5 benchmark table (PLAN.md Phase 5): policies x difficulty levels, mean +- 95% CI over seeds.

    python scripts/benchmark_table.py [--out docs/benchmark.md]

For every policy and seed below, finds the W&B run's Hugging Face folder (its summary's hf_url, with the
wandb-summary.json fallback), downloads the play.py results bench_l1 ... bench_l9 and bench_l5_full (written by the
p5-bench-* launches: held-out maps, test seed 1001, 60 tiles per level, 1000 episodes each), and writes a markdown
table of success and collision rates: the mean over seeds and a 95% confidence interval from Student's t (with 3
seeds, t = 4.30, so the intervals are wide: they describe seed-to-seed variation, not episode noise).
"""

from __future__ import annotations

import argparse
import functools
import json
import math
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import wandb_summary  # noqa: E402

# (label, description, {seed: W&B run id}).
# Docs: phase3-depth-student.md (§6.1, §9, §10.1), phase4-robustness.md §5.1.
POLICIES = [
    ("Teacher (privileged)", "lidar ring + 4 nearest obstacles, heading and soft-ceiling terms",
     {"42": "vam5p6dd", "1": "56j6n22n", "2": "arrqs6y5"}),
    ("Depth student, feed-forward", "CNN + MLP, distilled from the heading teacher",
     {"42": "jziy8wep", "1": "sfzu8umn", "2": "nqbifc1z"}),
    ("Depth student, GRU", "CNN + GRU, distilled from the teacher above (Phase 3 result)",
     {"42": "uke1cqz8", "1": "x5bl74jf", "2": "gik2yxvq"}),
    ("Depth student, GRU, randomized", "trained under domain randomization (Phase 4 result)",
     {"42": "0g9bvtcl", "1": "bmylysop", "2": "jegy71of"}),
]  # fmt: skip
CONDITIONS = [("bench_l1", "L1"), ("bench_l3", "L3"), ("bench_l5", "L5"), ("bench_l7", "L7"), ("bench_l9", "L9"),
              ("bench_l5_full", "L5 randomized")]  # fmt: skip
T_975 = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776}  # Student's t, two-sided 95%, by degrees of freedom


def mean_ci(values: list[float]) -> tuple[float, float]:
    """Mean and the half-width of its 95% confidence interval (0 for a single value)."""
    n = len(values)
    m = sum(values) / n
    if n < 2:
        return m, 0.0
    sd = math.sqrt(sum((v - m) ** 2 for v in values) / (n - 1))
    return m, T_975.get(n - 1, 1.96) * sd / math.sqrt(n)


def cell(values: list[float]) -> str:
    m, h = mean_ci(values)
    return f"{m:.1f} ± {h:.1f}" if len(values) > 1 else f"{m:.1f}"


@functools.cache
def hf_url_of(run_id: str) -> str | None:
    """The run's Hugging Face folder (one W&B lookup per run, however many results it has)."""
    import wandb

    run = wandb.Api(timeout=60).run(f"{os.environ['WANDB_ENTITY']}/{os.environ['WANDB_PROJECT']}/{run_id}")
    return wandb_summary.summary_value(run, "hf_url")


def fetch(run_id: str, name: str, cache: Path) -> dict | None:
    from huggingface_hub import hf_hub_download

    hf_url = hf_url_of(run_id)
    if not hf_url:
        return None
    path = hf_url.split("/tree/main/", 1)[-1] + f"/play/{name}.json"
    try:
        local = hf_hub_download(os.environ["HF_REPO_ID"], path, token=os.environ.get("HF_TOKEN"), local_dir=str(cache))
    except Exception:  # noqa: BLE001
        return None
    return json.loads(Path(local).read_text())


def rate(result: dict, key: str) -> float:
    return 100.0 * result[key].get("rate", result[key].get("mean"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "benchmark.md")
    parser.add_argument("--cache", type=Path, default=REPO_ROOT / "logs" / "benchmark")
    args = parser.parse_args()
    from dotenv import load_dotenv

    load_dotenv(REPO_ROOT / ".env")
    rows: dict[str, dict[str, dict[str, list[float]]]] = {}
    missing = []
    for label, _, seeds in POLICIES:
        rows[label] = {c: {"success": [], "collision": []} for c, _ in CONDITIONS}
        for seed, run_id in seeds.items():
            for name, _ in CONDITIONS:
                result = fetch(run_id, name, args.cache)
                if result is None:
                    missing.append(f"{label} s{seed} {name}")
                    continue
                rows[label][name]["success"].append(rate(result, "Metrics/success_rate"))
                rows[label][name]["collision"].append(rate(result, "Episode_Termination/collision"))
    header = "| Policy | " + " | ".join(h for _, h in CONDITIONS) + " |\n|---|" + "---:|" * len(CONDITIONS) + "\n"
    lines = [
        "# Benchmark",
        "",
        "Held-out maps (test seed 1001, 60 layouts per level), 1000 episodes per cell and seed.",
        "Mean over 3 seeds ± 95% confidence interval (Student's t). Generated by `scripts/benchmark_table.py`.",
        "",
        "## Success (%)",
        "",
        header.rstrip("\n"),
    ]
    for label, _, _ in POLICIES:
        lines.append(f"| {label} | " + " | ".join(cell(rows[label][c]["success"]) for c, _ in CONDITIONS) + " |")
    lines += ["", "## Collisions (%)", "", header.rstrip("\n")]
    for label, _, _ in POLICIES:
        lines.append(f"| {label} | " + " | ".join(cell(rows[label][c]["collision"]) for c, _ in CONDITIONS) + " |")
    lines += ["", "## Policies", ""]
    lines += [f"- **{label}**: {desc}. W&B runs: " + ", ".join(f"s{s} `{r}`" for s, r in seeds.items())
              for label, desc, seeds in POLICIES]  # fmt: skip
    lines += [
        "",
        "\"L5 randomized\": level 5 under full domain randomization (docs/phase4-robustness.md §2); the depth",
        "policies also with depth noise × 2.",
    ]
    if missing:
        lines += ["", "Missing results: " + ", ".join(missing)]
    args.out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
